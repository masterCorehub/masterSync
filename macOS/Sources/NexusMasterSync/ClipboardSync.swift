import AppKit
import Foundation
import ImageIO
import NexusCore
import UniformTypeIdentifiers

struct ClipboardItem: Codable, Identifiable {
    var id = Wire.id()
    let text: String
    let date: Date
    var pinned = false
}

@MainActor
final class ClipboardSync: ObservableObject {
    @Published private(set) var items: [ClipboardItem] = []
    @Published private(set) var skipNext = false
    @Published private(set) var error: String?
    var recordHistory = false
    var forward: ((String) -> Void)?
    var forwardImage: ((Data, String, String) -> Void)?

    private var changeCount: Int
    private let board: NSPasteboard
    private let file: URL
    private let excludedTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                              "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
    private let imageTypes = [UTType.png, .jpeg, .gif, .webP, .heic, .heif, .tiff]

    init(file: URL, board: NSPasteboard = .general) {
        self.file = file
        self.board = board
        changeCount = board.changeCount
        if let data = try? Data(contentsOf: file),
           let entries = try? JSONDecoder().decode([ClipboardItem].self, from: data) { items = entries }
    }

    func tick(sync: Bool, imagePeer: String?) {
        guard board.changeCount != changeCount else { return }
        changeCount = board.changeCount
        guard sync, excludedTypes.isDisjoint(with: (board.types ?? []).map(\.rawValue)) else { return }
        if let imagePeer, let type = imageTypes.first(where: { board.types?.contains(.init($0.identifier)) == true }),
           let bytes = board.data(forType: .init(type.identifier)) {
            if skipNext { skipNext = false; return }
            let expectedCount = changeCount
            Task {
                let image = await Task.detached(priority: .utility) { Self.imageForSending(bytes, type: type) }.value
                guard board.changeCount == expectedCount else { return }
                if let image {
                    error = nil
                    forwardImage?(image.0, image.1, imagePeer)
                } else {
                    error = "A imagem copiada é maior que 8 MB ou está em um formato incompatível."
                }
            }
            return
        }
        guard let text = board.string(forType: .string), Self.canSync(text) else { return }
        if skipNext { skipNext = false; return }
        record(text)
        forward?(text)
    }

    func receive(_ message: Message) {
        guard message.sensitive != true, let text = message.text, Self.canSync(text) else { return }
        apply(text)
        if skipNext { skipNext = false; return }
        record(text)
    }

    func receive(_ event: ADBClipboardEvent) {
        switch event {
        case .text(let text):
            var message = Message("clipboard")
            message.text = text
            receive(message)
        case .image(let bytes, let mime):
            applyImage(bytes, mime: mime)
        }
    }

    func apply(_ text: String) {
        board.clearContents()
        board.setString(text, forType: .string)
        // Remember the write counter so the next poll cannot echo the received text.
        changeCount = board.changeCount
    }

    func applyImage(_ bytes: Data, mime: String) {
        guard let type = UTType(mimeType: mime), let source = Self.safeImage(bytes),
              CGImageSourceGetType(source) as String? == type.identifier else { return }
        board.clearContents()
        board.setData(bytes, forType: NSPasteboard.PasteboardType(type.identifier))
        changeCount = board.changeCount
    }

    private nonisolated static func imageForSending(_ bytes: Data, type: UTType) -> (Data, String)? {
        guard bytes.count <= 64 * 1024 * 1024, let source = safeImage(bytes) else { return nil }
        if let mime = type.preferredMIMEType, ClipboardImages.formats.contains(mime), bytes.count <= ClipboardImages.limit {
            return (bytes, mime)
        }
        // macOS often supplies TIFF. PNG can be pasted by supported Android editors.
        let data = NSMutableData()
        guard let image = CGImageSourceCreateImageAtIndex(source, 0, nil),
              let destination = CGImageDestinationCreateWithData(data, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(destination, image, nil)
        guard CGImageDestinationFinalize(destination), data.length <= ClipboardImages.limit else { return nil }
        return (Data(referencing: data), "image/png")
    }

    private nonisolated static func safeImage(_ bytes: Data) -> CGImageSource? {
        guard let source = CGImageSourceCreateWithData(bytes as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int,
              width > 0, (1...16_384).contains(height), width <= 24_000_000 / height else { return nil }
        return source
    }

    func ignoreNext() { skipNext = true }

    func pin(_ id: String) {
        guard let item = items.firstIndex(where: { $0.id == id }) else { return }
        items[item].pinned.toggle()
        save()
    }

    func delete(_ id: String) {
        items.removeAll { $0.id == id }
        save()
    }

    func clear() {
        items.removeAll()
        save()
    }

    private static func canSync(_ text: String) -> Bool {
        !text.isEmpty && text.utf8.count <= 32 * 1024
    }

    private func record(_ text: String) {
        guard recordHistory, items.first?.text != text else { return }
        items.insert(ClipboardItem(text: text, date: .now), at: 0)
        if items.count > 100, let oldest = items.lastIndex(where: { !$0.pinned }) { items.remove(at: oldest) }
        save()
    }

    private func save() {
        do {
            try FileManager.default.createDirectory(at: file.deletingLastPathComponent(),
                withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
            try JSONEncoder().encode(items).write(to: file, options: .atomic)
            error = nil
        } catch {
            self.error = "Não foi possível atualizar o histórico local. \(error.localizedDescription)"
        }
    }
}
